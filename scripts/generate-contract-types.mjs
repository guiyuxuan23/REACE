import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const contract = new URL('../contracts/openapi.yaml', import.meta.url);
const target = new URL('../packages/shared-contracts/v1.ts', import.meta.url);
const rendered = '// Generated by npm run generate:types. Edit contracts/ instead.\n' + astToString(await openapiTS(contract));

if (process.argv.includes('--write')) {
  await writeFile(target, rendered);
} else if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== rendered) {
  throw new Error('Shared API types have drifted. Run npm run generate:types.');
}
